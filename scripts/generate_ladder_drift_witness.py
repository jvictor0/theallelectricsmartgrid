#!/usr/bin/env python3
"""Freeze an untrusted Fourier proposal as exact rational Lean data.

This does not certify an invariant graph, a residual, or an average. The
coordinate inverse is computed over the rationals; no floating-point inverse
is asserted to be exact. Ordinary Lean builds consume the emitted definitions
without running this producer or loading its numerical input.
"""

import argparse
import hashlib
import json
from fractions import Fraction
from pathlib import Path

from check_ladder_periodic_enclosure import rational_inverse


def literal(value):
    if isinstance(value, list):
        return "![" + ", ".join(literal(v) for v in value) + "]"
    value = Fraction(value)
    if value.denominator == 1:
        return str(value.numerator)
    return f"({value.numerator}/{value.denominator})"


def profile_coefficients(data):
    """Real Fourier coefficients, retaining both halves of the complex fit."""
    chart = data["chart"]
    real = chart["coefficientsReal"]
    imag = chart["coefficientsImag"]
    count = len(real)
    assert count == len(imag) and count % 2 == 0
    assert all(len(row) == 3 for row in real + imag)
    highest = max(min(n, count-n) for n in range(count)
                  if any(real[n]) or any(imag[n]))
    assert highest < count//2, "Nyquist term needs separate handling"
    cosine = [[real[0][j]] + [real[n][j]+real[-n][j]
               for n in range(1, highest+1)] for j in range(3)]
    sine = [[Fraction(0)] + [imag[-n][j]-imag[n][j]
             for n in range(1, highest+1)] for j in range(3)]
    return cosine, sine


def emit(source):
    # Parsing decimals directly as rationals avoids a second binary64 rounding.
    data = json.loads(source, parse_float=Fraction)
    transform = data["chart"]["transform"]
    inverse = rational_inverse(transform)
    cosine, sine = profile_coefficients(data)
    highest = len(cosine[0])-1
    correction = max(data["results"], key=lambda row: row["highest"])
    potential = correction["potential"]
    correction_highest = correction["highest"]
    assert len(potential) == 2*correction_highest
    correction_cosine = [[Fraction(0)]+[potential[2*n][j]
        for n in range(correction_highest)] for j in range(3)]
    correction_sine = [[Fraction(0)]+[potential[2*n+1][j]
        for n in range(correction_highest)] for j in range(3)]
    lines = [
        "import DSP.Analysis.TrigPolynomial",
        "import Mathlib.Data.Matrix.Mul",
        "",
        "/-! Generated by scripts/generate_ladder_drift_witness.py.",
        "Exact proposal data only: no invariance or measurement claim.",
        f"Source SHA256: {hashlib.sha256(source.encode()).hexdigest()} -/",
        "",
        "namespace DSP.NaiveReuppingLadder.HarmonicBalance.Certificates.DriftChartData",
        "set_option maxRecDepth 100000",
        "",
        "def transformRat : Matrix (Fin 4) (Fin 4) ℚ := " + literal(transform),
        "def inverseRat : Matrix (Fin 4) (Fin 4) ℚ := " + literal(inverse),
        f"def profileCosine : Fin 3 → Fin {highest+1} → ℚ := " + literal(cosine),
        f"def profileSine : Fin 3 → Fin {highest+1} → ℚ := " + literal(sine),
        f"def profilePolynomial (j : Fin 3) : TrigPolynomial {highest+1} :=",
        "  ⟨profileCosine j, profileSine j⟩",
        "",
        "/-- Components: coherent real, coherent imaginary, total power. -/",
        "def meanRat : Fin 3 → ℚ := " + literal(correction["mean"]),
        f"def correctionCosine : Fin 3 → Fin {correction_highest+1} → ℚ := " + literal(correction_cosine),
        f"def correctionSine : Fin 3 → Fin {correction_highest+1} → ℚ := " + literal(correction_sine),
        f"def correctionPolynomial (j : Fin 3) : TrigPolynomial {correction_highest+1} :=",
        "  ⟨correctionCosine j, correctionSine j⟩",
        "",
        "end DSP.NaiveReuppingLadder.HarmonicBalance.Certificates.DriftChartData",
        "",
    ]
    return "\n".join(lines)


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path,
                        default=root/"build/results/ladder-drift-certificate/averages.json")
    parser.add_argument("--output", type=Path, default=root/(
        "formal/DSP/Filters/NaiveReuppingLadder/HarmonicBalance/Certificates/DriftChartData.lean"))
    args = parser.parse_args()
    args.output.write_text(emit(args.input.read_text()))
    print(f"Wrote exact proposal definitions to {args.output}; no dynamic bounds certified.")


if __name__ == "__main__":
    main()
