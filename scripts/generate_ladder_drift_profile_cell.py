#!/usr/bin/env python3
"""Propose one whole Fourier-profile cell for exact Lean replay.

This tests the concrete chart-preparation witness format. It is not a ladder
dynamics, invariant-curve, or response certificate. Numerical operations here
are untrusted; emitted boxes must pass their Lean containment checks.
"""

import json
from decimal import Decimal as D
from fractions import Fraction
from pathlib import Path

from check_ladder_periodic_enclosure import I, Interval, sine_cosine
from generate_ladder_interval_witness import box
from generate_ladder_drift_witness import literal, profile_coefficients


def interval(value):
    lo, hi = Fraction(value.lo), Fraction(value.hi)
    width = hi-lo
    assert width >= 0
    return f"interval {literal(lo)} {width.numerator} {width.denominator}"


def vector(values):
    return "![" + ", ".join(interval(v) for v in values) + "]"


def propose(root, center='2.5', half_width='0.0002', digits=6):
    source = root/"build/results/ladder-drift-certificate/averages.json"
    cosine, sine = profile_coefficients(json.loads(source.read_text(), parse_float=Fraction))
    count = len(cosine[0])
    assert count == 81
    base = [box(sine_cosine(I(center), kind)+Interval(D("-1e-18"), D("1e-18")), 22)
            for kind in [False, True]]
    carriers = [[I(1), I(0)]]
    for _ in range(count-1):
        c, s = carriers[-1]
        carriers.append([box(c*base[0]-s*base[1], 22), box(s*base[0]+c*base[1], 22)])
    ranges, point_ranges = [], []
    for _ in range(3):
        point_ranges.append([box(sum((I(cosine[j][n])*carriers[n][0]+
            I(sine[j][n])*carriers[n][1] for n in range(count)), I(0)), 22) for j in range(3)])
        ranges.append([box(sum((
            I(cosine[j][n])*(carriers[n][0]+Interval(-D(n)*D(half_width), D(n)*D(half_width)))+
            I(sine[j][n])*(carriers[n][1]+Interval(-D(n)*D(half_width), D(n)*D(half_width)))
            for n in range(count)), I(0)), digits) for j in range(3)])
        cosine, sine = ([[n*sine[j][n] for n in range(count)] for j in range(3)],
                        [[-n*cosine[j][n] for n in range(count)] for j in range(3)])
    return {"base": base, "carriers": carriers, "ranges": ranges, "pointRanges": point_ranges}


def main():
    root = Path(__file__).resolve().parents[1]
    proposal = propose(root)
    base, carriers, ranges = [proposal[k] for k in ["base", "carriers", "ranges"]]
    lines = [
        "import DSP.Analysis.TrigPolynomial.HarmonicEnclosure",
        "import DSP.Filters.NaiveReuppingLadder.HarmonicBalance.Certificates.DriftChartData",
        "",
        "/-! Generated by scripts/generate_ladder_drift_profile_cell.py.",
        "Proposal data for one profile cell; no dynamic bounds asserted. -/",
        "namespace DSP.NaiveReuppingLadder.HarmonicBalance.Certificates.DriftProfileCellData",
        "open LeanCert.Core TrigPolynomial",
        "set_option maxRecDepth 100000",
        "def interval (lo : ℚ) (widthNumerator widthDenominator : ℕ) : IntervalRat :=",
        "  ⟨lo, lo+widthNumerator/widthDenominator, le_add_of_nonneg_right",
        "    (div_nonneg (Nat.cast_nonneg _) (Nat.cast_nonneg _))⟩",
        "def angle : IntervalRat := interval (12499/5000) 1 2500",
        "def pointAngle : IntervalRat := IntervalRat.singleton (5/2)",
        "def base : Carrier := " + vector(base),
        "def carrierData : Array Carrier := #[\n" + ",\n".join(map(vector, carriers)) + "\n]",
        "def carrier (n : ℕ) : Carrier := carrierData[n]?.getD (fun _ => IntervalRat.singleton 0)",
        "def ranges : Fin 3 → Fin 3 → IntervalRat := ![" + ",\n".join(map(vector, ranges)) + "]",
        "def pointRanges : Fin 3 → Fin 3 → IntervalRat := ![" + ",\n".join(map(vector, proposal["pointRanges"])) + "]",
        "def polynomial (order coordinate : Fin 3) : TrigPolynomial 81 :=",
        "  TrigPolynomial.derivative^[order.val] (DriftChartData.profilePolynomial coordinate)",
        "end DSP.NaiveReuppingLadder.HarmonicBalance.Certificates.DriftProfileCellData",
        "",
    ]
    output = root/("formal/DSP/Filters/NaiveReuppingLadder/HarmonicBalance/Certificates/"
                   "DriftProfileCellData.lean")
    output.write_text("\n".join(lines))
    print("Proposed profile/first/second derivative ranges:")
    for row in ranges:
        print([v.record() for v in row])
    print(f"Wrote {output}; Lean replay required.")


if __name__ == "__main__":
    main()
