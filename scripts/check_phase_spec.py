#!/usr/bin/env python3
"""Review gates for the phase model's C++ correspondence, not C++ verification."""
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "formal/PhaseTime"


def check():
    manifest = json.loads((SPEC / "traceability.json").read_text())
    contracts = json.loads((SPEC / "requirements.json").read_text())
    sources = {}
    for path, expected in manifest["files"].items():
        data = (ROOT / path).read_bytes()
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError(f"C++ drift: {path}; review correspondence before updating SHA-256")
        sources[path] = data.decode()
    locations = {}
    for key, anchors in manifest["anchors"].items():
        if not anchors:
            raise ValueError(f"empty source anchor: {key}")
        locations[key] = []
        for anchor in anchors:
            path, symbol = anchor["path"], anchor["symbol"]
            source = sources[path]
            if source.count(symbol) != 1:
                raise ValueError(f"missing or ambiguous source anchor: {key}: {symbol}")
            line = source[:source.index(symbol)].count("\n") + 1
            locations[key].append((path, line, symbol))
    references = set()
    for path in SPEC.glob("*.lean"):
        for key in re.findall(r"@cpp\s+([a-z_]+):", path.read_text()):
            if key not in locations:
                raise ValueError(f"unknown source anchor {key} in {path.name}")
            references.add(key)
    if references != locations.keys():
        raise ValueError(f"anchors without model references: {locations.keys() - references}")
    ids = set()
    report = ["# Phase-time contracts", "",
              "Generated by `make lean-test`. Proofs apply to the mathematical model; source links are reviewed correspondence.", ""]
    for contract in contracts:
        if contract["id"] in ids or contract["status"] != "proved":
            raise ValueError(f"duplicate or unproved contract: {contract['id']}")
        ids.add(contract["id"])
        if not contract["theorems"] or not contract["anchors"]:
            raise ValueError(f"missing proof or source: {contract['id']}")
        report.extend([f"## {contract['id']}", "", contract["requirement"], "",
                       "Lean: " + ", ".join(f"`{t}`" for t in contract["theorems"]) + ".", ""])
        for key in contract["anchors"]:
            for path, line, symbol in locations[key]:
                report.append(f"- [{path}:{line}](../../{path}#L{line}) — `{symbol}`")
        report.append("")
    output = ROOT / "build/lean/phase-contracts.md"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(report))
    print(f"Phase-time source audit: {len(sources)} files, {len(locations)} anchors, {len(contracts)} contracts.")
    print(f"Contract index: {output}")


if __name__ == "__main__":
    try:
        check()
    except (ValueError, KeyError, OSError) as error:
        print(f"Phase-time specification audit failed: {error}", file=sys.stderr)
        sys.exit(1)
